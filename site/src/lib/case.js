import { calculateEvidenceLevel } from './calculations.js';

export function createCase() {
  const timestamp = new Date();
  const suffix = timestamp.toISOString().replace(/[-:TZ.]/g, '').slice(0, 14);
  return {
    schema_version: '0.1.0',
    case_id: `OPV-${suffix}`,
    title: 'Untitled observation',
    created_at: timestamp.toISOString(),
    privacy: 'private',
    observation_summary: '',
    evidence_level: 0,
    verdict: 'insufficient-evidence',
    assets: [],
    calibration: {
      horizontal_field_of_view_deg: null,
      horizontal_pixels: null,
      vertical_pixels: null,
      frame_rate_fps: null,
      status: 'unknown',
    },
    measurements: [],
    limitations: [
      'Object identity is not established.',
      'True range and physical size are not established unless independently measured.',
    ],
    review: {
      conventional_checks: [],
      reviewer_notes: '',
    },
  };
}

export async function hashFile(file) {
  if (!(file instanceof Blob)) throw new TypeError('A browser File or Blob is required.');
  const digest = await crypto.subtle.digest('SHA-256', await file.arrayBuffer());
  return [...new Uint8Array(digest)].map((byte) => byte.toString(16).padStart(2, '0')).join('');
}

export function refreshEvidenceLevel(caseData) {
  caseData.evidence_level = calculateEvidenceLevel(caseData);
  return caseData.evidence_level;
}

export function validateCase(caseData) {
  const errors = [];
  if (caseData?.schema_version !== '0.1.0') errors.push('Unsupported schema version.');
  if (!/^OPV-[A-Z0-9-]+$/.test(caseData?.case_id || '')) errors.push('Invalid case ID.');
  if (!String(caseData?.title || '').trim()) errors.push('A case title is required.');
  if (!Array.isArray(caseData?.assets)) errors.push('Assets must be an array.');
  if (!Array.isArray(caseData?.measurements)) errors.push('Measurements must be an array.');
  if (!Number.isInteger(caseData?.evidence_level) || caseData.evidence_level < 0 || caseData.evidence_level > 7) {
    errors.push('Evidence level must be an integer from 0 through 7.');
  }
  for (const asset of caseData?.assets || []) {
    if (!/^[a-f0-9]{64}$/.test(asset.sha256 || '')) errors.push(`Asset ${asset.name || ''} has an invalid SHA-256 value.`);
    if (asset.asset_class === 'generated' && asset.is_evidence !== false) errors.push('Generated assets must set is_evidence to false.');
  }
  return { valid: errors.length === 0, errors };
}

export function safeFilename(value, extension) {
  const stem = String(value || 'opv-case')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '') || 'opv-case';
  return `${stem}.${extension}`;
}

export function downloadText(filename, content, mediaType = 'text/plain') {
  const url = URL.createObjectURL(new Blob([content], { type: mediaType }));
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  anchor.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function buildHtmlReport(caseData) {
  const escape = (value) => String(value ?? '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
  const assets = caseData.assets.map((asset) => `<li><strong>${escape(asset.name)}</strong> — ${escape(asset.asset_class)} — <code>${escape(asset.sha256)}</code></li>`).join('');
  const measurements = caseData.measurements.map((measurement) => `<li>${escape(measurement.pixel_extent)} px → ${escape(measurement.angular_extent_deg)}° (${escape(measurement.status)})</li>`).join('');
  const limitations = caseData.limitations.map((item) => `<li>${escape(item)}</li>`).join('');
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${escape(caseData.title)}</title>
<style>body{font-family:system-ui,sans-serif;max-width:780px;margin:40px auto;padding:0 20px;line-height:1.55;color:#172033}code{overflow-wrap:anywhere}section{margin:28px 0;padding-top:8px;border-top:1px solid #d7dce5}.badge{display:inline-block;border:1px solid #aeb7c7;border-radius:999px;padding:4px 10px;margin-right:8px}</style></head>
<body><h1>${escape(caseData.title)}</h1><p><span class="badge">Evidence level ${caseData.evidence_level}</span><span class="badge">${escape(caseData.verdict)}</span></p>
<p>${escape(caseData.observation_summary)}</p><section><h2>Assets</h2><ul>${assets || '<li>None</li>'}</ul></section>
<section><h2>Calibration</h2><pre>${escape(JSON.stringify(caseData.calibration, null, 2))}</pre></section>
<section><h2>Measurements</h2><ul>${measurements || '<li>None</li>'}</ul></section>
<section><h2>Limitations</h2><ul>${limitations}</ul></section><p>Generated by Open Phenomenon Verification v0.1.0.</p></body></html>`;
}
